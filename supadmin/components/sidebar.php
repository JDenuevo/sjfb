<script>
  document.addEventListener("DOMContentLoaded", function () {
    const currentPage = window.location.pathname.split("/").pop(); // gets current file like 'products.php'
    const sidebarLinks = document.querySelectorAll("#hs-application-sidebar a");

    sidebarLinks.forEach(link => {
      const href = link.getAttribute("href");

      if (href === currentPage) {
        link.classList.add(
          "bg-orange-500",  // highlight bg
          "text-white", // text color
          "font-semibold"  // make it stand out
        );
      } else {
        link.classList.remove("bg-orange-500", "text-white", "font-semibold");
      }
    });
  });
</script>
