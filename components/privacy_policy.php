// ── Privacy Policy modal ─────────────────────────────────────────────────────────────
function openModal(PrivacyID) {
  document.getElementById(PrivacyID)?.classList.remove('hidden');
  document.body.classList.add('overflow-hidden');
}

function closeModal(PrivacyID) {
  document.getElementById(PrivacyID)?.classList.add('hidden');
  document.body.classList.remove('overflow-hidden');
}

// Close on backdrop click
document.getElementById('privacyModal')?.addEventListener('click', function (e) {
  if (e.target === this) closeModal('privacyModal');
});

// Close on Escape key
document.addEventListener('keydown', function (e) {
  if (e.key === 'Escape') closeModal('privacyModal');
});
